# -*- coding: UTF-8 -*-
"""
Step 04: for each "test" (person, candidate auid) of an *ambiguous*
collection, compares their references with those of the reference
panel/domain computed by step 03, to validate whether citation overlap
truly distinguishes the correct match from the wrong ones.


INPUT FOLDER (step 03 data)

Selects a folder produced by step 03
(data/output/citations/community_unambiguous/<mode>_<min-researchers as 4
digits>_<collection>/<ys>-<ye>/) and extracts mode, min_researchers,
collection, year_start, year_end from its path.

If --citations-folder is not specified, shows a numbered list of all the
leaf-level subfolders (with no further subfolders) found under
data/output/citations/community_unambiguous/ and asks the user to pick one.


REQUIREMENTS ON THE COLLECTION (-c/--collection)

Must be run only on the *ambiguous* collections (erc_ambiguous_surname or
erc_ambiguous_surname_initial), the ones with several documents per
person and the "match" field (1/0) generated by step 02. The script
refuses to start (ERROR) if:
  - --collection does not contain the substring "_ambiguous_" in its name;
  - any document read does not have the "match" field (typical of the
    *unambiguous* collections).


OUTPUT 1: raw JSON (papers/references per test)

For each document of the collection and for each of its
match_scopus.auid, searches scopus_papers for the papers of that author
published in the [year_start, year_end] range (inclusive bounds, taken
from the path chosen above) and, for each paper, retrieves from
scopus_papers_references the cited scopus-ids. The result (one dictionary
for each document/auid pair, with "auid", "_id_source" of the source
document in erc, "papers" and "references") is saved to a JSON file in
data/output/citations/authors_ambiguous/. The queries are cached per auid
(the same candidate can reappear on several rows).


OUTPUT 2: on-screen report and TSV

For each author, compares their references with those of their panel (if
mode == panel) or domain (if mode == domain) as computed by step 03
(reading the <panel_or_domain>.json file inside citations_folder). The
report shows: panel/domain, "match" field (ground truth 1/0 taken from
the source document), number of the author's references, number of
references of the panel/domain, size of the intersection, and
percentage. If the author's panel/domain does not appear among the files
produced by step 03, the derived numeric values are set to -1 (different
from 0, which instead indicates an empty but computable intersection).

For each row, the erc document with the same _id_source as the document
from -c/--collection is retrieved from the erc collection (cached) and
all its fields are reported as the initial columns of the TSV, saved to
data/output/overlap/ (the raw JSON instead goes to
data/output/citations/authors_ambiguous/, see above). Fields that are
lists are joined with " - "; for "projects" only project_id is reported
(not acronym).


COMPUTING "n_people_unit" (unambiguous people in the panel/domain)

Computed by querying the unambiguous collection used by step 03 to
generate citations_folder (deduced from the path, "collection_from_folder"),
NOT the ambiguous collection in use: each ambiguous document represents a
test (person, candidate auid), not a person to count.

The value is also compared with the number of AUIDs in the "auids" field
of the step 03 JSON file for that same panel/domain: if the two numbers
do not match (typically because the file is stale relative to the last
run of step 02/03), a warning is printed and the value computed now from
Mongo is used anyway (more up to date).


--force: this script has no "unchanged" check to skip (it always
recomputes and rewrites both files on every run, there being no
granularity to save on - see the discussion in session). The option is
accepted only for interface consistency with the other pipeline steps
(e.g. for an orchestrator that passes --force to all steps at once); it
does not change the script's behavior.
"""
import argparse
import csv
import json
import os
from collections import Counter

from bson import ObjectId
from pymongo import MongoClient

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))


def rel(path):
    """path relative to SCRIPT_DIR, only for display in the help text."""
    return os.path.relpath(path, SCRIPT_DIR)


DEFAULT_DB = "scopus-fossr"
DEFAULT_COLLECTION = "erc_ambiguous_surname"
DEFAULT_CITATIONS_ROOT = os.path.join(SCRIPT_DIR, "data", "output", "citations", "community_unambiguous")
DEFAULT_AUTHORS_JSON_FOLDER = os.path.join(SCRIPT_DIR, "data", "output", "citations", "authors_ambiguous")
DEFAULT_OVERLAP_FOLDER = os.path.join(SCRIPT_DIR, "data", "output", "overlap")
SOURCE_COLLECTION = "erc"

ERC_COLUMNS = [
    "_id", "scopus_author_id", "indexed_name", "given_name", "surname",
    "name_in_project_dataset", "n_panels", "panels", "n_domains", "domains",
    "n_projects", "projects", "source_file", "imported_at",
]


class ResultEncoder(json.JSONEncoder):
    def default(self, obj):
        if isinstance(obj, set):
            return list(obj)
        if isinstance(obj, ObjectId):
            return str(obj)
        return super().default(obj)


def find_leaf_folders(root):
    """returns, sorted, all the subfolders of root that have no
    subfolders of their own (leaf-level folders)."""
    leaves = []
    for dirpath, dirnames, filenames in os.walk(root):
        if not dirnames:
            leaves.append(dirpath)
    return sorted(leaves)


def choose_folder_interactively(root):
    leaves = find_leaf_folders(root)
    if not leaves:
        raise SystemExit(f"no results folder found under {root}")

    print(f"folders available under {root}:")
    for i, folder in enumerate(leaves, start=1):
        rel_path = os.path.relpath(folder, root)
        print(f"  {i}) {rel_path}")

    while True:
        choice = input(f"choose a folder [1-{len(leaves)}]: ").strip()
        if choice.isdigit() and 1 <= int(choice) <= len(leaves):
            return leaves[int(choice) - 1]
        print("invalid choice, try again.")


def parse_citations_folder(folder):
    """extracts year_start/year_end from the last path component
    (e.g. "2016-2023") and mode/min_researchers/collection from the
    second-to-last, which has the schema <mode>_<min_researchers as 4
    digits>_<collection> (e.g. "panel_0005_erc_unambiguous_surname" ->
    mode="panel", min_researchers=5, collection="erc_unambiguous_surname")."""
    folder = folder.rstrip(os.sep)
    years_part = os.path.basename(folder)
    mode_collection_part = os.path.basename(os.path.dirname(folder))

    year_start_str, _, year_end_str = years_part.partition("-")
    year_start = int(year_start_str)
    year_end = int(year_end_str)

    mode, min_researchers_str, collection_from_folder = mode_collection_part.split("_", 2)

    return {
        "year_start": year_start,
        "year_end": year_end,
        "mode": mode,
        "min_researchers": int(min_researchers_str),
        "collection_from_folder": collection_from_folder,
    }


def fetch_auid_references(auid, year_start, year_end, mongo_papers, mongo_papers_references):
    """same query logic as step 03: for the AUID, for each year in the
    [year_start, year_end] range (inclusive bounds), retrieves the
    published papers and the cited scopus-ids from their reference list."""
    papers = []
    references = set()

    for year in range(year_start, year_end + 1):
        year_papers = [
            el["_id"] for el in mongo_papers.find(
                {"$and": [{"author.authid": auid}, {"pg:scopus-pub-year": str(year)}]},
                {"_id": 1},
            )
        ]
        papers.extend(year_papers)

        for paper in year_papers:
            temp = mongo_papers_references.find_one(
                {"_id": paper}, {"references.scopus-id": 1, "@total-references": 1}
            )
            if (temp is not None) and ("references" in temp):
                references.update(el["scopus-id"] for el in temp["references"])

    return papers, references


def load_unit_data(unit_code, citations_folder, cache):
    """loads (with cache) the data computed by step 03 for the
    panel/domain unit_code from the file <citations_folder>/<unit_code>.json:
    the set of references (merging all years present) and the number of
    AUIDs in the file's "auids" field. Returns None if the file does not
    exist (panel/domain not computed by step 03)."""
    if unit_code in cache:
        return cache[unit_code]

    fn = os.path.join(citations_folder, f"{unit_code}.json")
    if not os.path.isfile(fn):
        cache[unit_code] = None
        return None

    with open(fn) as f:
        data = json.load(f)

    references = set()
    for key, value in data.items():
        if key == "auids":
            continue
        references.update(value.get("references", []))

    result = {"references": references, "n_auids": len(data.get("auids", []))}
    cache[unit_code] = result
    return result


def compute_n_people_by_unit(db, collection_name, unit_field):
    """counts, for the *unambiguous* collection collection_name (1
    document per person), how many people have each panel/domain."""
    docs = list(db[collection_name].find({}, {unit_field: 1}))
    counts = Counter()
    for doc in docs:
        for u in set(doc.get(unit_field, [])):
            counts[u] += 1
    return counts


def flatten_erc_doc(erc_doc):
    """flattens a document of the erc collection into string columns for
    the TSV: lists are joined with " - "; for "projects" only project_id
    is reported (not acronym)."""
    if erc_doc is None:
        return {col: "" for col in ERC_COLUMNS}

    panels_str = " - ".join(p.get("panel", "") for p in erc_doc.get("panels", []))
    domains_str = " - ".join(erc_doc.get("domains", []))
    projects_str = " - ".join(p.get("project_id", "") for p in erc_doc.get("projects", []))

    return {
        "_id": str(erc_doc.get("_id", "")),
        "scopus_author_id": erc_doc.get("scopus_author_id", ""),
        "indexed_name": erc_doc.get("indexed_name", ""),
        "given_name": erc_doc.get("given_name", ""),
        "surname": erc_doc.get("surname", ""),
        "name_in_project_dataset": erc_doc.get("name_in_project_dataset", ""),
        "n_panels": erc_doc.get("n_panels", ""),
        "panels": panels_str,
        "n_domains": erc_doc.get("n_domains", ""),
        "domains": domains_str,
        "n_projects": erc_doc.get("n_projects", ""),
        "projects": projects_str,
        "source_file": erc_doc.get("source_file", ""),
        "imported_at": str(erc_doc.get("imported_at", "")),
    }


def main():
    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument("--db", default=DEFAULT_DB,
                         help=f"MongoDB database (default: {DEFAULT_DB})")
    parser.add_argument("-c", "--collection", default=DEFAULT_COLLECTION,
                         help=f"MongoDB collection (default: {DEFAULT_COLLECTION}; "
                              f"other typical value: erc_ambiguous_surname_initial)")
    parser.add_argument("--citations-folder", default=None,
                         help="folder with the data computed at step 03 "
                              "(data/output/citations/community_unambiguous/<mode>_<min-researchers>_<collection>/<ys>-<ye>/). "
                              "If not specified, a numbered list is offered "
                              "among the leaf-level subfolders of "
                              f"{rel(DEFAULT_CITATIONS_ROOT)}")
    parser.add_argument("--force", action="store_true",
                         help="accepted for consistency with the other pipeline steps; "
                              "has no effect here (this script always recomputes and "
                              "rewrites both files, it has no check to skip)")
    args = parser.parse_args()

    if "_ambiguous_" not in args.collection:
        raise SystemExit(
            f"ERROR: --collection must be an *ambiguous* collection "
            f"(the name must contain '_ambiguous_'), got: '{args.collection}'"
        )

    citations_folder = args.citations_folder
    if citations_folder is None:
        citations_folder = choose_folder_interactively(DEFAULT_CITATIONS_ROOT)

    parsed = parse_citations_folder(citations_folder)

    print()
    print("=== arguments ===")
    print(f"db: {args.db}")
    print(f"collection: {args.collection}")
    print(f"citations_folder: {citations_folder}")

    print()
    print("=== variables computed from the path ===")
    print(f"year_start: {parsed['year_start']}")
    print(f"year_end: {parsed['year_end']}")
    print(f"mode: {parsed['mode']}")
    print(f"min_researchers (from path): {parsed['min_researchers']}")
    print(f"collection_from_folder: {parsed['collection_from_folder']}")

    year_start = parsed["year_start"]
    year_end = parsed["year_end"]

    client = MongoClient()
    db = client[args.db]
    mongo_papers = db.scopus_papers
    mongo_papers_references = db.scopus_papers_references
    mongo_erc = db[SOURCE_COLLECTION]

    mode = parsed["mode"]
    unit_field = "panels" if mode == "panel" else "domains"

    docs = list(db[args.collection].find(
        {}, {"_id_source": 1, "match_scopus.auid": 1, unit_field: 1, "match": 1}
    ))

    if not all("match" in doc for doc in docs):
        raise SystemExit(
            f"ERROR: some documents of '{args.collection}' do not have a 'match' field "
            f"(typical of *unambiguous* collections). This script must be run only on "
            f"*ambiguous* collections (generated by step 02 with the combinatorial expansion)."
        )

    # reference population (*unambiguous* people) per panel/domain,
    # computed on the unambiguous collection used by step 03 to
    # generate citations_folder (collection_from_folder)
    n_people_by_unit_mongo = compute_n_people_by_unit(db, parsed["collection_from_folder"], unit_field)

    unit_cache = {}
    erc_cache = {}
    auid_cache = {}
    warned_units = set()
    results = []
    overlap_rows = []
    for doc in docs:
        doc_id_source = doc.get("_id_source")

        if doc_id_source not in erc_cache:
            erc_cache[doc_id_source] = mongo_erc.find_one({"_id": doc_id_source})
        erc_columns = flatten_erc_doc(erc_cache[doc_id_source])

        unit_codes = sorted(set(doc.get(unit_field, [])))
        for match in doc.get("match_scopus", []):
            auid = match.get("auid")
            if not auid:
                continue
            print(doc_id_source, auid, "match=", doc.get("match"))

            if auid not in auid_cache:
                auid_cache[auid] = fetch_auid_references(
                    auid, year_start, year_end, mongo_papers, mongo_papers_references
                )
            papers, references = auid_cache[auid]

            results.append({
                "auid": auid,
                "_id_source": doc_id_source,
                "papers": papers,
                "references": references,
            })

            n_references_author = len(references)
            units_to_check = unit_codes if unit_codes else [None]
            for unit_code in units_to_check:
                unit_data = (
                    load_unit_data(unit_code, citations_folder, unit_cache)
                    if unit_code is not None else None
                )
                if unit_data is None:
                    n_references_unit = -1
                    n_overlap = -1
                    percentage = -1
                    n_people_unit = -1
                else:
                    n_references_unit = len(unit_data["references"])
                    n_overlap = len(references & unit_data["references"])
                    percentage = (n_overlap / n_references_author * 100) if n_references_author else 0

                    n_people_unit_mongo = n_people_by_unit_mongo.get(unit_code, 0)
                    n_people_unit_json = unit_data["n_auids"]
                    if n_people_unit_mongo != n_people_unit_json and unit_code not in warned_units:
                        warned_units.add(unit_code)
                        print(
                            f"WARNING: for '{unit_code}' the number of unambiguous people "
                            f"computed now on Mongo ({n_people_unit_mongo}, from "
                            f"'{parsed['collection_from_folder']}') does not match the number "
                            f"of auids in the step 03 JSON file ({n_people_unit_json}). "
                            f"Using the Mongo value ({n_people_unit_mongo}) because it reflects "
                            f"the collection's current state; the JSON file might be "
                            f"stale relative to the last run of step 02/03."
                        )
                    n_people_unit = n_people_unit_mongo

                row = dict(erc_columns)
                row.update({
                    "auid": auid,
                    "match": doc.get("match"),
                    "unit": unit_code,
                    "n_people_unit": n_people_unit,
                    "n_references_author": n_references_author,
                    "n_references_unit": n_references_unit,
                    "n_overlap": n_overlap,
                    "percentage": percentage,
                })
                overlap_rows.append(row)

    os.makedirs(DEFAULT_AUTHORS_JSON_FOLDER, exist_ok=True)
    min_researchers = parsed["min_researchers"]
    out_fn = os.path.join(DEFAULT_AUTHORS_JSON_FOLDER, f"step04_{mode}_{min_researchers:04d}_{args.collection}_{year_start}-{year_end}.json")
    with open(out_fn, "w") as f:
        json.dump(results, f, cls=ResultEncoder)

    tsv_columns = ERC_COLUMNS + [
        "auid", "match", "unit", "n_people_unit", "n_references_author",
        "n_references_unit", "n_overlap", "percentage",
    ]
    os.makedirs(DEFAULT_OVERLAP_FOLDER, exist_ok=True)
    out_tsv_fn = os.path.join(DEFAULT_OVERLAP_FOLDER, f"step04_{mode}_{min_researchers:04d}_{args.collection}_{year_start}-{year_end}.tsv")
    with open(out_tsv_fn, "w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=tsv_columns, delimiter="\t")
        writer.writeheader()
        writer.writerows(overlap_rows)

    print()
    print(f"documents processed: {len(docs)}")
    print(f"document/auid pairs saved: {len(results)}")
    print(f"output json: {out_fn}")
    print(f"output tsv: {out_tsv_fn}")

    print()
    print(f"=== author overlap references vs {mode} ===")
    header = (
        f"{'auid':<14}{'match':>6}{mode:<10}{'n_people_' + mode:>16}{'n_ref_author':>14}"
        f"{'n_ref_' + mode:>14}{'n_overlap':>12}{'percentage':>13}"
    )
    print(header)
    for row in overlap_rows:
        unit_label = row["unit"] if row["unit"] is not None else "N/A"
        pct = row["percentage"]
        pct_label = f"{pct:.1f}%" if pct != -1 else "-1"
        print(
            f"{row['auid']:<14}{row['match']:>6}{unit_label:<10}{row['n_people_unit']:>16}{row['n_references_author']:>14}"
            f"{row['n_references_unit']:>14}{row['n_overlap']:>12}{pct_label:>13}"
        )


if __name__ == "__main__":
    main()
